# 剔除欄位個數小於 300 的欄位
import pandas as pd
df = pd.read_csv("MData-new.csv")
df = df.drop(columns=[i for i in df.columns if df[i].count() < 300])
df

# 處理缺失值

# 特定情況給0 例如:用藥醫院不可能不登記所以NAN大概率是0
list1 = ['PROM','Maternal Fever','Chorioamnionitis','Antibiotic','NPO','Dopamin','Dobutamine','Epinephrine',
      'Milrinone','Ampicillin','Gentamicin']
df[list1] = df[list1].fillna(0)

df = df.dropna()

df

# 過濾完的資料呈現
df.info()

"""# **Die**"""

# 使用隨機森林分類器進行模型訓練並提取特徵
from sklearn.ensemble import RandomForestClassifier

X = df.drop('Die', axis=1)
y = df['Die']

model = RandomForestClassifier()
model.fit(X, y)

# 獲取特徵的重要性
importances = model.feature_importances_
importance_dict = dict(zip(X.columns, importances))
sorted_features = sorted(importance_dict.items(), key=lambda x: x[1], reverse=True)

# 重要的前4個特徵
top_n = 4
top_features = [feature for feature, importance in sorted_features[:top_n]]

# 特徵名稱存儲為陣列
important_array = top_features

important_array

from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, confusion_matrix, precision_score, recall_score, f1_score,roc_auc_score, roc_curve
import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np


# 特徵/標籤
X = df.drop(important_array,axis=1)
y = df['Die']

# 隨機森林參數
n_estimators = 40         # 樹
max_depth = 6          # 樹深度
min_samples_split = 45      # 分裂樣本數
min_samples_leaf = 12    # 樣本數
random_seed = 42          # 隨機種子

# 訓練模型
model = RandomForestClassifier(
                n_estimators=n_estimators,
                max_depth=max_depth,
                min_samples_split=min_samples_split,
                min_samples_leaf=min_samples_leaf,
                random_state=random_seed,
                class_weight='balanced'
                )
model.fit(X, y)

# 預測結果
y_pred = model.predict(X)

# 計算效能指標
accuracy = accuracy_score(y, y_pred)
precision = precision_score(y, y_pred)
recall = recall_score(y, y_pred)
f1 = f1_score(y, y_pred)

# 計算混淆矩陣來計算特異性
conf_matrix = confusion_matrix(y, y_pred)
tn, fp, fn, tp = conf_matrix.ravel()

# 特異性 = TN / (TN + FP)
specificity = tn / (tn + fp)

# 計算 AUC 分數
y_prob = model.predict_proba(X)[:, 1]
auc = roc_auc_score(y, y_prob)

# 顯示效能指標
print(f"Accuracy: {accuracy:.4f}")
print(f"Precision: {precision:.4f}")
print(f"Recall (Sensitivity): {recall:.4f}")
print(f"F1 Score: {f1:.4f}")
print(f"Specificity: {specificity:.4f}")
print(f"AUC: {auc:.4f}")

# 繪製 ROC 曲線
fpr, tpr, thresholds = roc_curve(y, y_prob)

plt.figure(figsize=(8, 6))
plt.plot(fpr, tpr, color='blue', label=f'ROC curve (AUC = {auc:.4f})')
plt.plot([0, 1], [0, 1], color='gray', linestyle='--')
plt.xlabel('False Positive Rate (FPR)')
plt.ylabel('True Positive Rate (TPR)')
plt.title('ROC Curve')
plt.legend(loc='lower right')
plt.show()

